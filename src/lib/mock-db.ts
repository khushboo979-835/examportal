// Helper to get fully hydrated products with subject and board
export function getHydratedProducts(): PDFProduct[] {
  return mockPDFProducts.map((p) => {
    const subject = mockSubjects.find((s) => s.id === p.subjectId);
    if (!subject) return p;

    const board = mockBoards.find((b) => b.id === subject.boardOrExamId);
    const category = board ? mockCategories.find((c) => c.id === board.categoryId) : undefined;

    return {
      ...p,
      subject: {
        ...subject,
        boardOrExam: board
          ? {
              ...board,
              category,
            }
          : undefined,
      },
    };
  });
}
